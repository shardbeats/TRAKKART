"""MORPH page: particle dissolve controls + morph playlist (up to 5 extra).

Split out of the MOTION video section (same mechanical-move rule as the
other panel modules): widget attribute names are unchanged so BINDINGS,
presets and tests keep working. A (src) always comes from the canvas;
the list holds B..F in play order (chain capped at 6 total, A + 5).
"""

from __future__ import annotations

from PySide6.QtWidgets import (
    QComboBox,
    QHBoxLayout,
    QLabel,
    QPushButton,
    QSpinBox,
    QVBoxLayout,
)
from app.ui.panels.widgets import hlab, tight, labeled_slider


def build_morph_section(win, g: QVBoxLayout) -> None:
    """Dissolve params (still single source) + morph image playlist."""
    hlab(g, "Dissolve (particle disperse):")
    from app.disintegrate import (DISINTEGRATE_MODES, DOT_SHAPES, EASE_MODES,
                                  MATCH_MODES, MORPH_PATHS, STAGGER_MODES)

    win.cmb_dissolve_mode = QComboBox()
    win.cmb_dissolve_mode.addItems(list(DISINTEGRATE_MODES))
    tight(win.cmb_dissolve_mode, 8)
    win.cmb_dissolve_mode.setToolTip("Particle field: wind/random legacy · burst/suction/vortex/rain/rise/wave/ripple/flow/spiral/stream/scatter/blocks (F1)")
    win.cmb_dissolve_mode.currentTextChanged.connect(lambda _: win._schedule_refresh())
    mrow = QHBoxLayout()
    mrow.addWidget(QLabel("Field:"))
    mrow.addWidget(win.cmb_dissolve_mode, 1)
    g.addLayout(mrow)
    win.cmb_dissolve_stagger = QComboBox()
    win.cmb_dissolve_stagger.addItems(list(STAGGER_MODES))
    tight(win.cmb_dissolve_stagger, 8)
    win.cmb_dissolve_stagger.setToolTip("Release order: off = legacy together · rank/radial/scan/sweep pour in waves")
    win.cmb_dissolve_stagger.currentTextChanged.connect(lambda _: win._schedule_refresh())
    srow = QHBoxLayout()
    srow.addWidget(QLabel("Stagger:"))
    srow.addWidget(win.cmb_dissolve_stagger, 1)
    g.addLayout(srow)
    win.cmb_dissolve_ease = QComboBox()
    win.cmb_dissolve_ease.addItems(list(EASE_MODES))
    tight(win.cmb_dissolve_ease, 8)
    win.cmb_dissolve_ease.setToolTip("Loop envelope: sine = legacy · cubic = sharper · linear = constant speed")
    win.cmb_dissolve_ease.currentTextChanged.connect(lambda _: win._schedule_refresh())
    erow = QHBoxLayout()
    erow.addWidget(QLabel("Ease:"))
    erow.addWidget(win.cmb_dissolve_ease, 1)
    g.addLayout(erow)
    win.sld_dissolve_dotsize, _ = labeled_slider(win, g, "Dots:", 1, 4, 1, "Max dot swell 1-4px with the envelope (1 = classic 1px dots)", div=1.0)
    win.sld_dissolve_travel, _ = labeled_slider(win, g, "Travel:", 0, 100, 100, "Dots pour A->B through destination matching (0 = classic cloud reform)", div=100.0)
    win.cmb_dissolve_path = QComboBox()
    win.cmb_dissolve_path.addItems(list(MORPH_PATHS))
    tight(win.cmb_dissolve_path, 8)
    win.cmb_dissolve_path.setToolTip("Travel flourish: pour = straight lerp · arc lifts mid-flight · swirl bows sideways · braid weaves (joints stay exact)")
    win.cmb_dissolve_path.currentTextChanged.connect(lambda _: win._schedule_refresh())
    prow = QHBoxLayout()
    prow.addWidget(QLabel("Path:"))
    prow.addWidget(win.cmb_dissolve_path, 1)
    g.addLayout(prow)
    win.cmb_dissolve_match = QComboBox()
    win.cmb_dissolve_match.addItems(list(MATCH_MODES))
    tight(win.cmb_dissolve_match, 8)
    win.cmb_dissolve_match.setToolTip("Travel pairing: smooth = organic pour (no block tear) · morton = legacy Z-order matching")
    win.cmb_dissolve_match.currentTextChanged.connect(lambda _: win._schedule_refresh())
    matchrow = QHBoxLayout()
    matchrow.addWidget(QLabel("Match:"))
    matchrow.addWidget(win.cmb_dissolve_match, 1)
    g.addLayout(matchrow)
    win.cmb_dissolve_dot_shape = QComboBox()
    win.cmb_dissolve_dot_shape.addItems(list(DOT_SHAPES))
    tight(win.cmb_dissolve_dot_shape, 8)
    win.cmb_dissolve_dot_shape.setToolTip("Dot raster: square = legacy kxk blocks · round = inscribed discs (needs Dots > 1)")
    win.cmb_dissolve_dot_shape.currentTextChanged.connect(lambda _: win._schedule_refresh())
    dshrow = QHBoxLayout()
    dshrow.addWidget(QLabel("Dots shape:"))
    dshrow.addWidget(win.cmb_dissolve_dot_shape, 1)
    g.addLayout(dshrow)
    win.sld_dissolve_tint, _ = labeled_slider(win, g, "Tint:", 0, 100, 0, "Source-color dots near home, fading as they disperse (0 = classic black dots)", div=100.0)
    win.sld_dissolve_trail, _ = labeled_slider(win, g, "Trail:", 0, 8, 0, "Fading ghost dots behind moving particles, normalized so long trails stay subtle (0 = off)", div=1.0)
    win.sld_dissolve_amount, _ = labeled_slider(win, g, "Amount:", 0, 200, 100, "Disperse strength 0=still · 100=classic · up to 200", div=100.0)
    win.sld_dissolve_speed, _ = labeled_slider(win, g, "Speed:", 25, 400, 100, "Traversals per clip 0.25-4.0x (1 = full sweep)", div=100.0)
    win.sld_dissolve_wind_x, _ = labeled_slider(win, g, "Wind X:", -500, 500, 120, "Horizontal wind px at full disperse")
    win.sld_dissolve_wind_y, _ = labeled_slider(win, g, "Wind Y:", -500, 500, -40, "Vertical wind px at full disperse")
    seed_row = QHBoxLayout()
    seed_row.addWidget(QLabel("Seed:"))
    win.spn_dissolve_seed = QSpinBox()
    win.spn_dissolve_seed.setRange(0, 999999)
    win.spn_dissolve_seed.setValue(53596)
    win.spn_dissolve_seed.setFixedWidth(80)
    win.spn_dissolve_seed.setToolTip("Deterministic pattern seed (same seed = same particles)")
    win.spn_dissolve_seed.valueChanged.connect(lambda _: win._schedule_refresh())
    seed_row.addWidget(win.spn_dissolve_seed)
    seed_row.addStretch()
    g.addLayout(seed_row)
    win.sld_dissolve_hold, _ = labeled_slider(win, g, "Hold:", 0, 30, 10, "Still pause per form 0-3.0s — adds time, Length is derived (each form reads)", div=10.0)
    from PySide6.QtWidgets import QCheckBox as _Chk

    win.chk_dissolve_shade = _Chk("Shade (Heckel)")
    win.chk_dissolve_shade.setChecked(False)
    win.chk_dissolve_shade.setToolTip("Dot size follows source darkness (needs Dots > 1; joints stay 1px). Off = uniform swell.")
    win.chk_dissolve_shade.stateChanged.connect(lambda _: win._schedule_refresh())
    g.addWidget(win.chk_dissolve_shade)

    win.chk_morph_loop = _Chk("Loop (last → first)")
    win.chk_morph_loop.setChecked(True)
    win.chk_morph_loop.setToolTip("Closed loop: the last image morphs back into the first (no hard cut). Off = ends on the last image.")
    win.chk_morph_loop.stateChanged.connect(lambda _: win._schedule_refresh())
    win.chk_morph_loop.stateChanged.connect(lambda _: win._sync_anim_ui())
    g.addWidget(win.chk_morph_loop)
    hlab(g, "Morph chain A->B->C... (A = canvas):")
    from PySide6.QtWidgets import QListWidget

    win.morph_list_widget = QListWidget()
    win.morph_list_widget.setMinimumHeight(90)
    win.morph_list_widget.setMaximumHeight(150)
    win.morph_list_widget.setToolTip("Play order after A. Add up to 5 (chain of 6 max).")
    win.morph_list_widget.itemSelectionChanged.connect(lambda: win._on_morph_selected())
    g.addWidget(win.morph_list_widget)
    brow = QHBoxLayout()
    win.btn_morph_pick = QPushButton("Add...")
    win.btn_morph_pick.setToolTip("Append an image to the chain (B, C, ... up to 5)")
    win.btn_morph_pick.clicked.connect(win._on_morph_pick)
    brow.addWidget(win.btn_morph_pick)
    win.btn_morph_remove = QPushButton("Remove")
    win.btn_morph_remove.setFixedWidth(70)
    win.btn_morph_remove.setToolTip("Remove the selected chain image")
    win.btn_morph_remove.clicked.connect(win._on_morph_remove)
    brow.addWidget(win.btn_morph_remove)
    win.btn_morph_up = QPushButton("▲")
    win.btn_morph_up.setFixedWidth(36)
    win.btn_morph_up.setToolTip("Move selected earlier in the chain")
    win.btn_morph_up.clicked.connect(win._on_morph_up)
    brow.addWidget(win.btn_morph_up)
    win.btn_morph_down = QPushButton("▼")
    win.btn_morph_down.setFixedWidth(36)
    win.btn_morph_down.setToolTip("Move selected later in the chain")
    win.btn_morph_down.clicked.connect(win._on_morph_down)
    brow.addWidget(win.btn_morph_down)
    win.btn_morph_clear = QPushButton("Clear")
    win.btn_morph_clear.setFixedWidth(56)
    win.btn_morph_clear.setToolTip("Forget the whole chain")
    win.btn_morph_clear.clicked.connect(win._on_morph_clear)
    brow.addWidget(win.btn_morph_clear)
    g.addLayout(brow)
    win.lbl_morph = QLabel("B: (none — morph falls back to dissolve)")
    win.lbl_morph.setWordWrap(True)
    win.lbl_morph.setObjectName("subtitleLabel")
    g.addWidget(win.lbl_morph)
    win.lbl_morph_short = QLabel("")
    win.lbl_morph_short.setWordWrap(True)
    win.lbl_morph_short.setObjectName("subtitleLabel")
    win.lbl_morph_short.setToolTip("Transition frames per leg (exact plan budget). 2 or fewer means joints only: hard cut with no pour or mid-flight color.")
    g.addWidget(win.lbl_morph_short)
    win.lbl_morph_crop = QLabel("Crop: select a chain image")
    win.lbl_morph_crop.setWordWrap(True)
    win.lbl_morph_crop.setObjectName("subtitleLabel")
    g.addWidget(win.lbl_morph_crop)
    win.btn_morph_crop = QPushButton("Adjust crop...")
    win.btn_morph_crop.setToolTip("Visual crop of the selected chain image (frame locked to A)")
    win.btn_morph_crop.clicked.connect(win._on_morph_crop)
    g.addWidget(win.btn_morph_crop)
